"""Render the LiteLLM proxy config from the definition."""

import asyncio
import contextlib
import os
import re
import tempfile
import time
from collections.abc import Mapping
from datetime import datetime
from pathlib import Path
from typing import Any

import httpx
import structlog
import yaml

from swfactory.definition.models import Definition

log = structlog.get_logger()
GATEWAY_SERVICE_LABEL = "com.docker.compose.service=gateway"
READY_POLL_S = 2.0

LITELLM_PREFIX: Mapping[str, str] = {
    "vertex_ai": "vertex_ai",
    "gemini": "gemini",
    "groq": "groq",
    "openrouter": "openrouter",
    "lm_studio": "lm_studio",
    "ollama": "ollama_chat",
    "openai_compatible": "openai",
    "anthropic_compatible": "anthropic",
}
LOCAL_KINDS = frozenset({"lm_studio", "ollama"})
_BASE_URL_KINDS = frozenset({"lm_studio", "ollama", "openai_compatible", "anthropic_compatible"})
VERTEX_PROJECT_PARAM = "vertex_project"
VERTEX_LOCATION_PARAM = "vertex_location"
DEFAULT_PROJECT_ENV = "GOOGLE_CLOUD_PROJECT"
LITELLM_SETTINGS: Mapping[str, bool] = {
    "turn_off_message_logging": True,
    "redact_user_api_key_info": True,
}
SPEND_BATCH_S = 5
LITELLM_DB_POOL_LIMIT = 10


def _per_token(per_mtok: Any) -> float:
    return float(per_mtok) / 1_000_000


# The only environment variables a rendered config may reference. Anything else that starts with
# "os.environ/" would let a definition read the gateway's other secrets.
_ENV_REF = re.compile(
    r"os\.environ/((GEMINI|GROQ|OPENROUTER|BYO_[A-Z0-9_]+)_API_KEY|GOOGLE_CLOUD_PROJECT"
    r"|[A-Z][A-Z0-9_]*_PROJECT|LITELLM_MASTER_KEY)"
)


def _check_env_refs(params: dict[str, Any]) -> None:
    for key, value in params.items():
        if (
            isinstance(value, str)
            and value.startswith("os.environ/")
            and not _ENV_REF.fullmatch(value)
        ):
            raise ValueError(
                f"refusing to render {key}={value!r}: not an allowed environment reference"
            )


def render_litellm_config(defn: Definition) -> dict[str, Any]:
    providers = defn.factory.providers
    entries: list[dict[str, Any]] = []
    limited = False
    for alias, m in defn.factory.models.items():
        prov = providers[m.provider]
        params: dict[str, Any] = {"model": f"{LITELLM_PREFIX[prov.kind]}/{m.upstream_id}"}
        if prov.api_key_env:
            params["api_key"] = f"os.environ/{prov.api_key_env}"
        if prov.kind in _BASE_URL_KINDS and prov.base_url:
            params["api_base"] = prov.base_url
        if prov.kind == "vertex_ai":
            params[VERTEX_PROJECT_PARAM] = prov.project or (
                f"os.environ/{prov.project_env or DEFAULT_PROJECT_ENV}"
            )
            params[VERTEX_LOCATION_PARAM] = prov.location or "global"
        if m.rpm is not None:
            params["rpm"] = m.rpm
            limited = True
        if m.tpm is not None:
            params["tpm"] = m.tpm
            limited = True
        _check_env_refs(params)
        entry: dict[str, Any] = {"model_name": alias, "litellm_params": params}
        info: dict[str, Any] = {}
        if prov.kind in LOCAL_KINDS:
            info = {"input_cost_per_token": 0, "output_cost_per_token": 0}
        if m.price_in_per_mtok is not None:
            info["input_cost_per_token"] = _per_token(m.price_in_per_mtok)
        if m.price_out_per_mtok is not None:
            info["output_cost_per_token"] = _per_token(m.price_out_per_mtok)
        if info:
            entry["model_info"] = info
        entries.append(entry)
    cfg: dict[str, Any] = {
        "model_list": entries,
        "general_settings": {
            "master_key": "os.environ/LITELLM_MASTER_KEY",
            "proxy_batch_write_at": SPEND_BATCH_S,
            "database_connection_pool_limit": LITELLM_DB_POOL_LIMIT,
        },
        "litellm_settings": dict(LITELLM_SETTINGS),
    }
    if limited:
        cfg["router_settings"] = {"optional_pre_call_checks": ["enforce_model_rate_limits"]}
    return cfg


def config_text(defn: Definition, sha: str) -> str:
    """The generated header plus the YAML: exactly what ``factory gateway render`` writes."""
    header = f"# generated by factory gateway render from {sha}; do not edit\n"
    return header + yaml.safe_dump(render_litellm_config(defn), sort_keys=False)


def _started_ts(value: Any) -> float:
    if isinstance(value, int | float):
        return float(value)
    text = str(value or "")
    m = re.fullmatch(r"(\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d)(\.\d+)?(Z|[+-]\d\d:\d\d)", text)
    if not m:
        return 0.0
    frac = (m.group(2) or "")[:7]
    tz = "+00:00" if m.group(3) == "Z" else m.group(3)
    try:
        return datetime.fromisoformat(m.group(1) + frac + tz).timestamp()
    except ValueError:
        return 0.0


def _write_atomic(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".litellm-", suffix=".tmp")
    try:
        with os.fdopen(fd, "w") as f:
            f.write(text)
        os.chmod(tmp, 0o644)
        os.replace(tmp, path)
    except BaseException:
        with contextlib.suppress(OSError):
            os.unlink(tmp)
        raise


async def _wait_ready(url: str, timeout_s: int) -> None:
    deadline = time.monotonic() + timeout_s
    async with httpx.AsyncClient(timeout=5) as http:
        while True:
            try:
                if (await http.get(url)).status_code == 200:
                    return
            except httpx.HTTPError:
                pass
            if time.monotonic() >= deadline:
                raise TimeoutError(f"gateway not ready at {url} after {timeout_s}s")
            await asyncio.sleep(READY_POLL_S)


async def sync_gateway(
    defn: Definition,
    sha: str,
    client: Any,
    *,
    conf_path: Path,
    ready_url: str,
    ready_timeout_s: int = 120,
) -> bool:
    """Write the config when it differs and restart the gateway to load it (LiteLLM reads its
    config only at start). True when it restarted."""
    want = config_text(defn, sha)
    try:
        have = conf_path.read_text()
    except OSError:
        have = None
    changed = have != want
    if changed:
        await asyncio.to_thread(_write_atomic, conf_path, want)
    found = await asyncio.to_thread(
        client.containers.list, filters={"label": GATEWAY_SERVICE_LABEL}
    )
    if not found:
        log.warning("gateway.sync_no_container")
        return False
    container = found[0]
    stale = False
    if not changed:
        await asyncio.to_thread(container.reload)
        started = _started_ts((container.attrs.get("State") or {}).get("StartedAt"))
        stale = started < conf_path.stat().st_mtime
    if not (changed or stale):
        return False
    await asyncio.to_thread(container.restart, timeout=10)
    await _wait_ready(ready_url, ready_timeout_s)
    return True
