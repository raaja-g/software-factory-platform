import pytest

from swfactory.definition.loader import defaults_dir, load_definition
from swfactory.gateway.render import config_text, sync_gateway
from swfactory.settings import FactoryMode, Settings

SHA, SHA2 = "a" * 40, "b" * 40


def _defn():
    r = load_definition(str(defaults_dir()))
    assert r.definition is not None
    return r.definition


DEFN = _defn()


def _repoint(defn):
    models = dict(defn.factory.models)
    models["gemini-flash@vertex"] = models["gemini-flash@vertex"].model_copy(
        update={"upstream_id": "gemini-3.9-flash"}
    )
    return defn.model_copy(update={"factory": defn.factory.model_copy(update={"models": models})})


DEFN2 = _repoint(DEFN)


async def test_sync_writes_and_restarts_once(tmp_path, fake_docker, ready):
    conf = tmp_path / "litellm.yaml"
    assert await sync_gateway(DEFN, SHA, fake_docker, conf_path=conf, ready_url=ready.url) is True
    assert fake_docker.restarts == ["gateway"] and conf.read_text() == config_text(DEFN, SHA)
    assert conf.read_text().startswith(f"# generated by factory gateway render from {SHA}")
    assert await sync_gateway(
        DEFN, SHA, fake_docker, conf_path=conf, ready_url=ready.url
    ) is False and fake_docker.restarts == ["gateway"]


async def test_new_definition_rewrites_and_restarts(tmp_path, fake_docker, ready):
    conf = tmp_path / "litellm.yaml"
    await sync_gateway(DEFN, SHA, fake_docker, conf_path=conf, ready_url=ready.url)
    assert await sync_gateway(DEFN2, SHA2, fake_docker, conf_path=conf, ready_url=ready.url) is True
    assert fake_docker.restarts == ["gateway", "gateway"]
    assert "vertex_ai/gemini-3.9-flash" in conf.read_text()


async def test_restarts_gateway_older_than_its_file(tmp_path, fake_docker, ready):
    conf = tmp_path / "litellm.yaml"
    conf.write_text(config_text(DEFN, SHA))
    fake_docker.started_at["gateway"] = conf.stat().st_mtime - 60
    assert await sync_gateway(DEFN, SHA, fake_docker, conf_path=conf, ready_url=ready.url) is True


async def test_waits_for_readiness(tmp_path, fake_docker, ready):
    ready.script = [503, 503, 200]
    await sync_gateway(
        DEFN, SHA, fake_docker, conf_path=tmp_path / "litellm.yaml", ready_url=ready.url
    )
    assert ready.calls == 3


async def test_readiness_timeout_raises(tmp_path, fake_docker, ready):
    ready.script = [503]
    with pytest.raises(TimeoutError):
        await sync_gateway(
            DEFN,
            SHA,
            fake_docker,
            conf_path=tmp_path / "litellm.yaml",
            ready_url=ready.url,
            ready_timeout_s=0,
        )


def test_no_sync_by_default():
    assert Settings(mode=FactoryMode.PERSONAL).gateway_config_path is None  # pyright: ignore[reportCallIssue]


class WorkerEnv:
    def __init__(self, deps, docker, gateway, store):
        self.deps, self.docker, self.gateway, self.store = deps, docker, gateway, store

    async def activate(self, defn, sha):
        from swfactory.definition.loader import LoadResult

        assert await self.store.save(LoadResult(sha, "test", defn, ()))

    async def run_ticks(self, n):
        from swfactory.worker import catalog_tick

        for _ in range(n):
            await catalog_tick(self.deps)


